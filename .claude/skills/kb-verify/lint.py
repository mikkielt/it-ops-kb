HOME = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
sys.path.insert(0, os.path.join(HOME, "_tools"))
import build_index  # noqa: E402
import kbcommon  # noqa: E402
import kbfacts  # noqa: E402
import kbid  # noqa: E402
SID = kbid.SOURCE_ID  # hash source ids (S-k3f7q2zd) and legacy ones (S123)


SNIPPET = re.compile(r"^- SNIPPET:", re.M)
# A repository file url at a ref (GitHub raw or blob, GitLab -/raw or -/blob): group 1 is the ref, group 2 the file path.
PIN_FILE = (re.compile(r"^https://raw\.githubusercontent\.com/[^/]+/[^/]+/((?:refs/tags/)?[^/]+)/(.+)$"),
            re.compile(r"^https://github\.com/[^/]+/[^/]+/(?:blob|raw)/((?:refs/tags/)?[^/]+)/(.+)$"),
            re.compile(r"^https://[^/?#]+/.+?/-/(?:raw|blob)/((?:refs/tags/)?[^/?#]+)/(.+)$"))


def pinned_path_suffix(row):
    """The file path of a source row whose url is a repository file at a ref, else None (the path kbingest's drift
    check compares a CODE pointer with, `pin_parts(url)[3]`)."""
    url = (row.get("url") or "").strip()
    for rx in PIN_FILE:
        m = rx.match(url)
        if m and not m.group(1).startswith("-"):
            return urllib.parse.unquote(re.split(r"[?#]", m.group(2))[0])
    return None


def pointer_off_pin(ptr, ids, sources, note=""):
    """True when every cited source row is a pinned repository file and neither the pointer's path nor any other
    path-like word of the note (a note may name the file without a symbol, then point at another) matches one of
    their paths, as a whole or as trailing segments (the rule kbingest drift_findings applies). A citation of any
    other source (an artifact, a page) is not judged here."""
    rows = [sources[i] for i in ids if i in sources]
    paths = [pinned_path_suffix(r) for r in rows]
    if not paths or not all(paths):
        return False
    words = [ptr[0]] + re.findall(r"[\w.\-/]+\.\w+", note)
    return not any(x == w or x.endswith("/" + w) for x in paths for w in words)
# A fact that says it rests on a run of our own (kb/_self/content-rules.md, Facts and tags): "observed on|in|by|with|
# against|at|when|running|:", "measured" the same way, "probed", "the|a|this|that|same|one|each [word] probe
# on|of|against|in|with|showed|found|returned|gave|was|answered", "in the|a|one|two|three|each|both|these|those|N
# [word] probe(s)", or "in the|a|one|two|three|each|both|these|those|N [setting] run(s)" where the setting word is one of
# RUN_SETTING (headless, interactive, first, same ...). Deliberately narrow: "an observed failure", "measured behavior",
# "a liveness probe", "a `-c` probe" (the thing, not our run of it), "in the long run" and "in a pipeline run" do not match.
RUN_SETTING = (r"(?:headless|interactive|first|second|third|last|same|single|separate|repeated|test|local|live|manual"
               r"|own|our)")
OBSERVED_RUN = re.compile(
    r"\b(?:observed|measured)(?=\s*:|\s+(?:on|in|by|with|against|at|when|running)\b)"
    r"|\bprobed\b"
    r"|\b(?:the|a|this|that|same|one|each)\s+(?:\w+\s+)?probe\s+(?:on|of|against|in|with|showed|found|returned|gave|was|answered)\b"
    r"|\bin\s+(?:the|a|one|two|three|each|both|these|those|\d+)\s+(?:\w+\s+)?probes?\b"
    r"|\bin\s+(?:the|a|one|two|three|each|both|these|those|\d+)\s+(?:" + RUN_SETTING + r"\s+)?runs?\b", re.I)
# The version such a fact must state. A version has a version shape: three or more dotted parts (2.1.285), "version N",
# "vN", or two dotted parts (3.3) that are no measurement: not followed by a unit (2.5 s, 1.5 MB, 3.2 %), not after a
# protocol name (TLS 1.2) or a measuring word (took 2.5, about 2.5), and not marked approximate (~2.5).
VERSION_WORD = re.compile(r"\bv\d+(?:\.\d+)*\b|\bversion\s+\d+(?:\.\d+)*", re.I)
DOTTED = re.compile(r"(?<![\w.])\d+(?:\.\d+)+(?!\d)")
UNIT_AFTER = re.compile(
    r"\s*(?:%|(?:s|sec|secs|seconds?|ms|milliseconds?|min|mins|minutes?|h|hr|hrs|hours?|days?|[kmgt]i?b|bytes?|x|times"
    r"|percent|rows?|requests?|calls?|items?|events?|users?|devices?)\b)", re.I)
NOT_A_VERSION_BEFORE = re.compile(
    r"(?:\b(?:tls|ssl|dtls|https?|ipv|smb|ntlm|ssh|quic)\s*(?:version\s*|v)?"
    r"|\b(?:took|takes|taking|waited|waits|after|about|around|roughly|approximately|nearly|almost"
    r"|within|under|over|than)\s*|[~\u2248\u00b1<>]\s*)$", re.I)


def has_version(item):
    """Whether the text names a version of what ran (shapes above), not only a measurement."""
    for m in VERSION_WORD.finditer(item):
        if not NOT_A_VERSION_BEFORE.search(item[:m.start()]):
            return True
    for m in DOTTED.finditer(item):
        if m.group().count(".") >= 2:
            return True
        if not UNIT_AFTER.match(item, m.end()) and not NOT_A_VERSION_BEFORE.search(item[:m.start()]):
            return True
    return False


def unversioned_run(item, kinds):
    """Whether a Facts bullet is a DER fact resting on a run or probe that names no version (not a SNIPPET: its
    `context:` carries the versions)."""
    return ("DER" in kinds and not item.startswith("- SNIPPET:") and bool(OBSERVED_RUN.search(item))
            and not has_version(item))
FENCE = re.compile(r"^```(\w*)[^\n]*\n(.*?)^```", re.M | re.S)
# A second bullet joined onto a fact's line: a tag's closing bracket, optional spaces, then `- ` (`[DOC S1]- next`,
# `[DOC S1] - next`). A dash inside the fact (a range `1 - 3`, `-based`) is not after a tag and does not match.
JOINED_BULLET = re.compile(r"\s*- ")


def joined_bullets(text):
    """(line number, line) of each Facts line, outside a fenced block, where a tag is followed by `- `."""
    out, facts, fenced = [], False, False
    for n, ln in enumerate(text.split("\n"), 1):
        if ln.startswith("```"):
            fenced = not fenced
        elif not fenced and ln.startswith("## "):
            facts = ln.startswith("## Facts")
        elif facts and not fenced and any(JOINED_BULLET.match(ln, m.end()) for m in kbfacts.TAG.finditer(ln)):
            out.append((n, ln))
    return out


def snippet_problems(body):
    """What is wrong with each `- SNIPPET:` bullet and the fenced block below it."""
    out = []
    for m in SNIPPET.finditer(body):
        rest = body[m.start():]
        bullet = re.split(r"\n(?:\s*\n|(?=```)|(?=- )|(?=#))", rest, maxsplit=1)[0]
        what = " ".join(bullet[2:].split())[:60]
        if not re.search(r"\bcontext:", bullet):
            out.append(f"SNIPPET without `context:`: {what!r}")
        checked = re.search(r"\bchecked:\s*(\w+)", bullet)
        if not checked or checked.group(1) not in ("no", "syntax", "run"):
            out.append(f"SNIPPET without `checked: no|syntax|run`: {what!r}")
        kinds = set(kbfacts.kinds_of(kbfacts.tags_in(bullet)))
        if not kinds - {"UNK"}:
            out.append(f"SNIPPET without an evidence tag (DOC, CODE, DER or COMMUNITY): {what!r}")
        block = FENCE.match(rest[len(bullet):].lstrip("\n"))
        if not block:
            out.append(f"SNIPPET not followed by a fenced code block: {what!r}")
        elif checked and checked.group(1) == "syntax":
            lang, code = block.group(1).lower(), block.group(2)
            try:
                if lang == "json":
                    json.loads(code)
                elif lang == "toml":
                    import tomllib
                    tomllib.loads(code)
                elif lang == "python":
                    compile(code, "<snippet>", "exec")
            except ImportError:
                pass  # tomllib needs Python 3.11
            except Exception as e:  # noqa: BLE001 - any parse error is the finding
                out.append(f"SNIPPET says checked: syntax but its {lang} block does not parse ({type(e).__name__}): {what!r}")
    return out


def wanted(root, rel, prefixes):
    """Whether a root's file (rel: its path in the root) is selected by the prefixes (bare or qualified)."""
    return not prefixes or any(rel.startswith(a.rstrip("/")) or kbcommon.qualify(root, rel).startswith(a.rstrip("/"))
                               for a in prefixes)


def qualified(arg):
    """The prefix `arg` names as the qualified `<root>/<path>` wanted() compares: a path from the repository
    (`kb/public/<path>`) or an absolute one that lies under a root is rewritten; any other argument is returned as is."""
    a = arg.replace(os.sep, "/")
    full = os.path.normpath(a if os.path.isabs(a) else os.path.join(kbcommon.HOME, a))
    for root in kbcommon.roots():
        try:
            rel = os.path.relpath(full, root.path).replace(os.sep, "/")
        except ValueError:  # another drive
            continue
        if rel == ".":
            return root.name
        if rel != ".." and not rel.startswith("../"):
            return kbcommon.qualify(root, rel)
    return arg


def kb_self(path):
    """Whether `path` (from `kb/`, from the repository, or absolute) names an existing file or directory of the kb's
    own docs, `kb/_self/`, which are under no root and which a landing passes."""
    for base in (kbcommon.KB_DIR, kbcommon.HOME):
        full = os.path.normpath(os.path.join(base, path))
        if os.path.exists(full) and (full + os.sep).startswith(kbcommon.SELF + os.sep):
            return True
    return False


def refused(args):
    """The arguments (as qualified() gives them) that select nothing: no .md file of any root starts with it, it names
    no existing file or directory of `kb/_self/` (the kb's own docs are under no root, and a landing passes them), and
    git has no history of it in its root or in `kb/_self/` (a deleted article, which a landing's changed paths hold).
    A path that exists and is no article, or lies outside the roots and `kb/_self/` (a tool, README.md, `kb/`
    itself), is refused, history or not."""
    files = list(root_files())
    out = []
    for a in args:
        path = a.rstrip("/")
        if any(wanted(root, p, [a]) for root, p in files) or kb_self(path):
            continue
        root, rel = kbcommon.split(path)
        if root:
            home = (root.path, rel)
        elif path.startswith("_self/"):
            home = (kbcommon.KB_DIR, path)
        elif path.startswith("kb/_self/"):
            home = (kbcommon.HOME, path)
        else:
            home = None
        if (home and not os.path.exists(os.path.join(*home))
                and (git_out(home[0], "log", "-1", "--format=%H", "--", home[1]) or "").strip()):
            continue
        out.append(a)
    return out


def all_sources():
    """{id: row} over every root's _sources.csv (ids are unique across roots by their prefix)."""
    out = {}
    for root in kbcommon.roots():
        with open(os.path.join(root.path, kbcommon.SOURCES), encoding="utf-8-sig", newline="") as f:
            out.update((r["id"], r) for r in csv.DictReader(f))
    return out


def candidates(prefixes):
    """Print the CODE and SNIPPET migration candidates (see the module docstring); exit 0."""
    sources = all_sources()
    n_code = n_snip = 0
    for u in kbfacts.units(None):
        if prefixes and not any(u["path"].startswith(a.rstrip("/")) or u["path"].split("/", 1)[-1].startswith(a.rstrip("/"))
                                for a in prefixes):
            continue
        for part in u["tags"]:
            ids = [i for i in part["ids"] if i in sources]
            if part["kind"] == "DOC" and ids and all(kbfacts.code_file_source(sources[i])
                                                     and not kbfacts.contract_source(sources[i]) for i in ids):
                n_code += 1
                print(f"CODE-CANDIDATE {u['path']}:{u['line']}  {' '.join(ids)}  {' '.join(u['text'].split())[:90]}")
    for root, p in root_files():
        if p.startswith(("_", ".")) or not wanted(root, p, prefixes):
            continue
        lines = open(os.path.join(root.path, p), encoding="utf-8", errors="replace").read().split("\n")
        inside = False
        for i, ln in enumerate(lines):
            if not ln.startswith("```"):
                continue
            if not inside:
                prev = next((x for x in reversed(lines[:i]) if x.strip()), "")
                bullet = next((x for x in reversed(lines[:i]) if x.startswith("- ")), "")
                if not (prev.startswith(("- SNIPPET:", "  ")) and bullet.startswith("- SNIPPET:")):
                    n_snip += 1
                    print(f"SNIPPET-CANDIDATE {kbcommon.qualify(root, p)}:{i + 1}  {ln[3:] or '(no language)'}")
            inside = not inside
    print(f"code_candidates={n_code} snippet_candidates={n_snip}")
    return 0


def root_files():
    """(root, path in the root) of every .md file of every root, in order."""
    for root in kbcommon.roots():
        for p in sorted(glob.glob("**/*.md", root_dir=root.path, recursive=True)):
            yield root, p.replace(os.sep, "/")


def git_out(root, *args):
    """git's stdout run in the root's directory (a Root, or a directory), or None when it fails (no git, no work
    tree, no such revision)."""
    try:
        p = subprocess.run(["git", "-C", getattr(root, "path", root), *args], capture_output=True, text=True,
                           encoding="utf-8", errors="replace")
    except OSError:
        return None
    return p.stdout if p.returncode == 0 else None


def changed_articles(root, base):
    """The .md files of the root (paths in it) that differ from `base` or are untracked; None when the root is no git
    work tree or `base` names no commit (the new-fact rule then has nothing to compare with)."""
    if git_out(root, "rev-parse", "--verify", "--quiet", f"{base}^{{commit}}") is None:
        return None
    names = (git_out(root, "diff", "--name-only", "--relative", base, "--", ".") or "").splitlines()
    names += (git_out(root, "ls-files", "--others", "--exclude-standard") or "").splitlines()
    return {n for n in names if n.endswith(".md")}


def new_facts(root, base, p, text):
    """The tagged fact units of the article `p` (path in the root, current `text`) whose fact key is not among the
    facts of the file at `base`: every fact when the file is new there. Reworded facts are new, as anchors key them."""
    old = git_out(root, "show", f"{base}:./{p}")
    seen = {kbfacts.fact_key(u["text"]) for u in kbfacts.md_units(p, old)} if old else set()
    return [u for u in kbfacts.md_units(p, text) if kbfacts.fact_key(u["text"]) not in seen]


def microsoft_host(url):
    host = (urllib.parse.urlsplit(url or "").hostname or "").lower()
    return host == "microsoft.com" or host.endswith(".microsoft.com")


def quote_findings(p, text, root, base, sources, anchors):
    """(line, message) of each DOC fact the change added to the article `p` whose anchor says the page does not hold
    it: `unlocated:no-match`, or, where the source's reuse allows a quote and it is not a Microsoft page, an anchor
    with no quote or none at all (the module docstring)."""
    out = []
    for u in new_facts(root, base, p, text):
        key = kbfacts.fact_key(u["text"])
        claim = " ".join(kbfacts.TAG.sub(" ", u["text"]).split())[:60]
        for part in u["tags"]:
            if part["kind"] != "DOC":
                continue
            for sid in part["ids"]:
                row, src = anchors.get((key, p, sid)), sources.get(sid, {})
                quotable = (src.get("reuse") or "").strip() in ("copy", "quote") and not microsoft_host(src.get("url"))
                how = ""
                if row is None:
                    how = f"{sid} has no anchor with a quote for it yet" if quotable else ""
                elif row["status"] == "unlocated:no-match":
                    how = f"no passage of {sid}'s page holds it"
                elif row["status"] == "located" and not row["quote"] and quotable:
                    how = f"its anchor in {sid} holds no quote of the page"
                if how:
                    out.append((u["line"], f"DOC fact added in this change: {how} (give the quote it rests on: "
                                           f"factdiff.py anchor --file {p} --quotes CSV): {claim!r}"))
    return out


def lint_root(root, args, add, base="HEAD"):
    """The findings of one root (paths passed to add are qualified). `base` is the revision the new-fact rule counts
    facts added in the change from."""
    q = lambda p: kbcommon.qualify(root, p)  # noqa: E731
    at = lambda p: os.path.join(root.path, p)  # noqa: E731
    changed = changed_articles(root, base)
    if changed is None and base != "HEAD":
        add("WARN", root.name, f"--base {base} names no commit of this root's work tree: the added-fact rule did not run")
    anchors = {}
    if changed and os.path.exists(at(kbcommon.ANCHORS)):
        with open(at(kbcommon.ANCHORS), encoding="utf-8-sig", newline="") as f:
            anchors = {(r["fact"], r["path"], r["source_id"]): r for r in csv.DictReader(f)}
    with open(at(kbcommon.COVERAGE_CSV), encoding="utf-8-sig", newline="") as f:
        cov = {r["topic"]: r for r in csv.DictReader(f)}
    page = build_index.coverage_page(root=root)
    try:
        table = open(at(page), encoding="utf-8").read()
    except OSError:
        table = ""
    try:
        gen = {r["topic"]: r for r in build_index.build(root=root)[1]}
    except build_index.BuildError as e:
        sys.exit(f"ERROR cannot build the coverage index of root {root.name}: {e}")
    rebuild = "(run python3 _tools/build_index.py)"
    with open(at(kbcommon.SOURCES), encoding="utf-8-sig", newline="") as f:
        sources = {r["id"]: r for r in csv.DictReader(f)}
    for p in sorted(glob.glob("**/*.md", root_dir=root.path, recursive=True)):
        p = p.replace(os.sep, "/")
        if not wanted(root, p, args):
            continue
        text = open(at(p), encoding="utf-8", errors="replace").read()
        if not text.startswith("---\n") or "\ntopic:" not in text.split("\n---", 2)[0]:
            continue
        head, body = text.split("\n---", 2)[0], text.split("\n---", 2)[-1]
        fm = dict((k.strip(), v.strip()) for k, _, v in (ln.partition(":") for ln in head.splitlines()[1:]))
        topic, want = fm.get("topic", ""), p[:-3]
        if topic != want:
            add("ERROR", q(p), f"topic is {topic!r}, path says {want!r}")
        row = gen.get(topic or want)
        if row:  # None: a part of another topic (named in its `files:`), e.g. an artifact digest
            if cov.get(topic) != row:
                add("ERROR", q(p), f"_coverage.csv row is missing or out of date {rebuild}")
            if build_index.readme_table([row]).splitlines()[-2] not in table.splitlines():
                add("ERROR", q(p), f"{q(page)} coverage row is missing or out of date {rebuild}")
            for f in filter(None, row["files"].split(";")):
                if not os.path.exists(at(f)):
                    add("ERROR", q(p), f"_coverage.csv lists missing file {f} (fix `files:` in the front matter)")
        heads = re.findall(r"^## (.+)$", body, re.M)
        for s in ("Summary", "Facts", "Reference", "Examples"):
            if not any(h.startswith(s) for h in heads):
                add("ERROR", q(p), f"missing section ## {s}")
        if not re.search(r"^# ", body, re.M):
            add("WARN", q(p), "no '# ' title line")
        for tag in kbfacts.TAG.findall(body):
            for part in kbfacts.parse_tag(tag):
                if not part["ids"] and (part["kind"] in ("DOC", "CODE", "COMMUNITY") or (part["kind"] == "DER" and not part["note"])):
                    add("ERROR", q(p), f"{part['kind']} tag without a source id: {' '.join(tag.split())[:70]}")
                if part["kind"] == "CODE":
                    ptr = kbfacts.code_pointer(part)
                    if not ptr:
                        add("ERROR", q(p), f"CODE tag without a path#symbol pointer: {' '.join(tag.split())[:70]}")
                    elif pointer_off_pin(ptr, part["ids"], sources, part.get("note") or ""):
                        add("ERROR", q(p), f"CODE pointer {ptr[0]} matches no pinned path of {' '.join(part['ids'])}: {' '.join(tag.split())[:70]}")
                    for sid in part["ids"]:
                        if sid in sources and not kbfacts.pinned_source(sources[sid]):
                            add("ERROR", q(p), f"CODE cites {sid}, which is not pinned to a tag or commit (re-source it)")
        for problem in snippet_problems(body):
            add("ERROR", q(p), problem)
        m = re.search(r"^## Facts.*?$(.*?)(?=^## |\Z)", body, re.M | re.S)
        if m:
            for item in re.split(r"\n(?=- )", m.group(1)):
                item = item.strip()
                if not item.startswith("- "):
                    continue
                kinds = set(kbfacts.kinds_of(kbfacts.tags_in(item)))
                if not kinds:
                    add("ERROR", q(p), f"untagged fact: {item[2:80]!r}")
                elif len(kinds) > 1:
                    add("WARN", q(p), f"fact mixes tags {sorted(kinds)}: {item[2:60]!r}")
                if unversioned_run(item, kinds):
                    add("WARN", q(p), f"DER fact rests on a run or probe but names no version: {item[2:60]!r}")
        for n, ln in joined_bullets(text):
            add("ERROR", f"{q(p)}:{n}", f"Facts line holds a second bullet after its tag (split it): {ln.strip()[2:70]!r}")
        if changed and p in changed:
            for n, msg in quote_findings(p, text, root, base, sources, anchors):
                add("WARN", f"{q(p)}:{n}", msg)
        cited = {s for tag in re.findall(r"\[(?:DOC|CODE|DER|COMMUNITY)[^\]]*\]", body) for s in SID.findall(tag)}
        fms = set(SID.findall(fm.get("sources", "")))
        if fms - cited:
            add("WARN", q(p), f"header sources not cited in the body: {' '.join(sorted(fms - cited))}")
        if cited - fms:
            add("WARN", q(p), f"cited sources missing from the header: {' '.join(sorted(cited - fms))}")


def main():
    argv, base = sys.argv[1:], "HEAD"
    for i, a in enumerate(argv):
        if a == "--base" or a.startswith("--base="):
            if a == "--base" and i + 1 >= len(argv):
                sys.exit("lint.py: --base needs a revision")
            base = argv[i + 1] if a == "--base" else a.partition("=")[2]
            argv = [x for j, x in enumerate(argv) if j != i and not (a == "--base" and j == i + 1)]
            break
    given = [a for a in argv if a not in ("--json", "--candidates")]
    args = [qualified(a) for a in given]
    none = refused(args)
    if none:
        sys.exit("lint.py: no file of any root matches " + ", ".join(repr(g) for g, a in zip(given, args) if a in none)
                 + " (a path in its root, `<root>/<path>` or `kb/<root>/<path>`): nothing was linted")
    if "--candidates" in sys.argv:
        return candidates(args)
    out = []

    def add(level, path, msg):
        out.append({"level": level, "path": path, "message": msg})

    for root in kbcommon.roots():
        lint_root(root, args, add, base)

    if "--json" in sys.argv:
        print(json.dumps(out, indent=1))
    else:
        for x in out:
            print(f"{x['level']:<5} {x['path']}: {x['message']}")
        n = sum(1 for x in out if x["level"] == "ERROR")
        print(f"errors={n} warnings={len(out) - n}")
    sys.exit(1 if any(x["level"] == "ERROR" for x in out) else 0)


if __name__ == "__main__":
    sys.exit(main())
