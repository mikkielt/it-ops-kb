#!/usr/bin/env python3
"""Contract checks that _tools/check.py does not make (stdlib only). Reports only; never edits.

  lint.py                    every topic of every root (kbcommon.roots())
  lint.py auth public/dsc    only topics whose path starts with one of these prefixes (a path in its root, a
                             qualified path `<root>/<path>`, or that path from the repository, `kb/<root>/<path>`, or
                             absolute); findings name files by their qualified path. An argument that matches no file
                             of any root, is no file or directory of kb/_self/ (the kb's own docs, under no root) and
                             no path of a root or of kb/_self/ git has a history of (a deleted article, as a landing
                             passes it) exits 1 naming it, so a mistyped path, a file outside kb/ or kb/ itself
                             never reads as a clean lint
  lint.py --json             machine output
  lint.py --candidates [PREFIX...]   migration lists, not findings: DOC facts that cite only source-code files, not
                             published contracts such as schemas (CODE candidates; kbfacts.contract_source), and
                             fenced code blocks with no SNIPPET bullet above them (SNIPPET candidates)
  lint.py --base REV [PREFIX...]   the revision the facts added in the change are counted from (default HEAD: the
                             uncommitted change); see the last WARN below

ERROR (exit 1): topic id differs from the path; its _coverage.csv row or its root's _coverage.md row is missing or out of
date (both are generated by _tools/build_index.py from the front matter, so this means "run build_index.py");
coverage lists a missing file (fix the `files:` front matter); a missing section; a DOC, CODE or COMMUNITY tag part
without a source id, a bare [DER] (tags are parsed by _tools/kbfacts.py, the grammar is in its docstring); a Facts bullet with no tag;
a CODE part without a `path#symbol` pointer, whose pointer path matches no pinned file path of its sources, or citing a source that is not pinned to a tag or commit; a `SNIPPET:`
bullet without `context:`, a `checked: no|syntax|run` value, an evidence tag other than UNK, or a fenced block right
below it; a `checked: syntax` json, toml or python block that does not parse; a Facts line where a tag is followed by
`- `, a second bullet joined onto it (named by path:line).
WARN: no H1 title; a Facts bullet mixing tag kinds; a DER Facts bullet (not a SNIPPET) that says it rests on a run or
probe of our own (OBSERVED_RUN) and names no version (has_version: 2.1.285, 3.3, "version N", "vN"; a measurement
such as 2.5 s or TLS 1.2 is none); header source ids never cited in the body, or cited ids missing from the header; a
DOC fact the change added (its fact key, `kbfacts.fact_key`, is not among the file's facts at the base revision, or the
file is new), cited to a source whose page the root's `_anchors.csv` read as text, whose anchor is `unlocated:no-match`
or, where the source's reuse is `copy` or `quote` and its host is not microsoft.com, is located with no `quote` or is
missing: the page holds no passage for the fact, or the researcher's quote did not locate one (`factdiff.py anchor
--file F --quotes CSV`). A fact the change did not add, and a source that is no text (`not-text`, `fetch-error`,
`gone`), raise nothing, so the unlocated anchors already in the ledger are silent. The rule needs a git work tree.
"""
