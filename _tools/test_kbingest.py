def commit_files(path, files):
    r = Repo(path)
    Path(r.path).mkdir(parents=True)
    r.git("init", "-q", "-b", "main")
    for rel, text in files.items():
        r.write(rel, text)
    r.git("add", "-A")
    r.git("commit", "-q", "-m", "init")
    return r


