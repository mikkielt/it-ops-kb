TOOL_V1 = ("def keep(x):\n    return x\n\n\ndef change(x):\n    return x + 1\n\n\ndef gone(x):\n    return x\n\n\n"
           "def vanish():\n    return 0\n\n\nclass Widget:\n    def method(self):\n        return 1\n")
TOOL_V2 = ("# a new header comment\n# and another\n\ndef keep(x):\n    return x\n\n\ndef change(x):\n    return x + 2\n\n\n"
           "def gone2(x):\n    return x\n\n\nprint(gone(1))\n\n\nclass Widget:\n    def method(self):\n        return 1\n\n"
           "    def extra(self):\n        return 2\n")
DRIFT_HOST, DRIFT_PROJECT = "gitlab.corp.example.com", "ops/deploy"
# (key, file, anchor): the CODE facts of the fixture root, each citing its file at the first commit
DRIFT_FACTS = (
    ("keep", "app/tool.py", "keep"), ("change", "app/tool.py", "change"), ("gone", "app/tool.py", "gone"),
    ("vanish", "app/tool.py", "vanish"), ("method", "app/tool.py", "Widget.method"),
    ("moved", "lib/moved.go", "Moved"), ("removed", "lib/removed.ps1", "Remove-Me"),
    ("limit", "conf/settings.yaml", "limit"), ("name", "conf/settings.yaml", "name"),
    ("range-moved", "notes.txt", "L2-L3"), ("range-changed", "notes.txt", "L5"), ("range-same", "notes.txt", "L1-L1"),
)


class Drift:
    """A repository with two commits and a kb root whose CODE facts cite the first."""

    def __init__(self, base):
        self.repo = commit_files(base / "deploy", {
            "app/tool.py": TOOL_V1, "lib/moved.go": "func Moved() int {\n\treturn 1\n}\n",
            "lib/removed.ps1": "function Remove-Me {\n  1\n}\n", "conf/settings.yaml": "limit: 5\nname: x\n",
            "notes.txt": "alpha\nbeta\ngamma\ndelta\nepsilon\nzeta\n"})
        self.repo.git("remote", "add", "origin", f"https://jan.kowalski:tok@{DRIFT_HOST}/{DRIFT_PROJECT}.git")
        self.old = self.repo.rev("HEAD")
        self.repo.write("app/tool.py", TOOL_V2)
        self.repo.write("conf/settings.yaml", "limit: 10\nname: x\n")
        self.repo.write("notes.txt", "alpha\nnew\nbeta\ngamma\ndelta\nEPSILON\nzeta\n")
        self.repo.git("mv", "lib/moved.go", "lib/moved_here.go")
        self.repo.git("rm", "-q", "lib/removed.ps1")
        self.repo.git("add", "-A")
        self.repo.git("commit", "-q", "-m", "second")
        self.new = self.repo.rev("HEAD")
        self.root = base / "codefix"
        self.write_root()

    def url(self, rel, commit=None, project=DRIFT_PROJECT):
        return kbingest.pin_url("gitlab", DRIFT_HOST, project, commit or self.old, rel)

    def write_root(self):
        root = self.root
        (root / "code").mkdir(parents=True)
        (root / "_root.md").write_text("---\nroot: codefix\nid_prefix: FXT\nvisibility: internal\n"
                                       "description: drift fixture\n---\n", encoding="utf-8", newline="\n")
        urls = {rel: self.url(rel) for _, rel, _ in DRIFT_FACTS}
        urls["other.go"] = self.url("other.go", project="ops/other")
        urls["unknown.go"] = self.url("unknown.go", commit="ab" * 20)
        sids = {rel: kbid.source_id(u, "FXT") for rel, u in urls.items()}
        rows = ["id,url,title,publisher,licence,reuse,retrieved_utc,version_or_date,artifact_sha256,used_in,superseded_by"]
        rows += [f"{sids[rel]},{u},{rel},corp.example.com,internal,quote,2026-09-26,,,code/tool.md," for rel, u in urls.items()]
        (root / "_sources.csv").write_text("\n".join(rows) + "\n", encoding="utf-8", newline="\n")
        lines = ["---", "topic: code/tool", "priority: P1", "retrieved_utc: 2026-09-26", "status: partial", "---", "",
                 "# Tool", "", "## Facts"]
        self.at = {}
        for key, rel, anchor in DRIFT_FACTS + (("other", "other.go", "Run"), ("unknown", "unknown.go", "Run")):
            self.at[key] = len(lines) + 1
            lines.append(f"- The fact {key} reads {anchor}. [CODE {sids[rel]}: {rel}#{anchor}]")
        lines.append(f"- A documented fact stays out. [DOC {sids['app/tool.py']}]")
        (root / "code" / "tool.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    def run(self, *args, repo=None):
        return run("drift", str(repo or self.repo.path), *args, env=git_env(KB_ROOTS=str(self.root)))

    def findings(self, out):
        """{kb line: (kind, path#symbol, detail)} of the finding lines."""
        got = {}
        for ln in out.splitlines():
            if ln.startswith("finding\t"):
                _, kind, where, _sid, label, detail = ln.split("\t")
                got[int(where.rsplit(":", 1)[1])] = (kind, label, detail)
        return got


